static void draw_char_6x12(uint8_t *buf, char c, int x, int y)
{
	if (c < 32 || c > 126) {
		return;
	}
	const uint8_t *font_data = font_6x12[c - 32];
	for (int row = 0; row < 12; row++) {
		uint8_t row_data = font_data[row];
		for (int col = 0; col < 6; col++) {
			if (row_data & (0x80 >> col)) {
				set_pixel_direct(buf, x + col, y + row);
			}
		}
	}
}

static void draw_string_6x12(uint8_t *buf, const char *str, int x, int y)
{
	int cur_x = x;
	while (*str && cur_x <= OLED_WIDTH - 6) {
		draw_char_6x12(buf, *str, cur_x, y);
		cur_x += 6;
		str++;
	}
}

/* Render battery %, charge/discharge state (+ cycle count), and voltage. */
void oled_show_battery(uint8_t pct, bool charging, uint32_t mv,
		       const char *state, uint32_t cycles)
{
	char line[24];

	oled_clear_buffer();

	/* Line 1: "Bat: NN%" */
	snprintk(line, sizeof(line), "Bat: %u%%", pct);
	draw_string_6x12(display_buffer, line, 2, 2);

	/* Line 2: state + cycle count (e.g. "DISCHARGE #5") */
	snprintk(line, sizeof(line), "%s #%u", state ? state : "-", cycles);
	draw_string_6x12(display_buffer, line, 2, 18);

	/* Line 3: voltage */
	snprintk(line, sizeof(line), "%u mV", mv);
	draw_string_6x12(display_buffer, line, 2, 34);

	oled_write_buffer();
}

/* Draw a simple test pattern */
static void oled_draw_test_pattern(void)
{
	oled_clear_buffer();

	/* Draw border */
	for (int x = 0; x < OLED_WIDTH; x++) {
		/* Top and bottom rows */
		display_buffer[x] = 0x80;
		display_buffer[OLED_BUF_SIZE - OLED_WIDTH + x] = 0x01;
	}
	for (int y = 1; y < OLED_HEIGHT / 8 - 1; y++) {
		/* Left and right columns */
		display_buffer[y * OLED_WIDTH] = 0xFF;
		display_buffer[(y + 1) * OLED_WIDTH - 1] = 0xFF;
	}

	/* Draw diagonal line */
	for (int i = 0; i < OLED_WIDTH && i < OLED_HEIGHT; i++) {
		int byte_idx = (i / 8) * OLED_WIDTH + i;
		int bit_idx = i % 8;
		if (byte_idx < OLED_BUF_SIZE) {
			display_buffer[byte_idx] |= (1 << bit_idx);
		}
	}

	oled_write_buffer();
	LOG_INF("Test pattern displayed");
}

/* Draw animated circle */
static void oled_draw_circle(int radius, int center_x, int center_y)
{
	oled_clear_buffer();

	/* Draw circle using midpoint circle algorithm */
	int x = radius;
	int y = 0;
	int err = 0;

	while (x >= y) {
		/* Draw 8 octants */
		int points[8][2] = {
			{center_x + x, center_y + y},
			{center_x + y, center_y + x},
			{center_x - y, center_y + x},
			{center_x - x, center_y + y},
			{center_x - x, center_y - y},
			{center_x - y, center_y - x},
			{center_x + y, center_y - x},
			{center_x + x, center_y - y}
		};

		for (int i = 0; i < 8; i++) {
			int px = points[i][0];
			int py = points[i][1];
			if (px >= 0 && px < OLED_WIDTH && py >= 0 && py < OLED_HEIGHT) {
				int byte_idx = (py / 8) * OLED_WIDTH + px;
				int bit_idx = py % 8;
				if (byte_idx < OLED_BUF_SIZE) {
					display_buffer[byte_idx] |= (1 << bit_idx);
				}
			}
		}

		if (err <= 0) {
			y += 1;
			err += 2 * y + 1;
		}
		if (err > 0) {
			x -= 1;
			err -= 2 * x + 1;
		}
	}

	oled_write_buffer();
}

/* Initialize OLED display */
int oled_init(void)
{
	LOG_INF("Initializing OLED display...");

	/* Get display device from devicetree */
	display_dev = DEVICE_DT_GET(DT_NODELABEL(ch1115));
	if (!device_is_ready(display_dev)) {
		LOG_ERR("Display device not ready");
		return -ENODEV;
	}

	LOG_INF("OLED display ready (%dx%d)", OLED_WIDTH, OLED_HEIGHT);

	/* Clear display on startup */
	oled_clear_buffer();
	oled_write_buffer();

	return 0;
}

